import { readFile } from "node:fs/promises";
import { join } from "node:path";

import { strToU8, zipSync } from "fflate";
import { NextResponse } from "next/server";

import { Tone } from "@/generated/prisma/enums";
import { demoLetterDate, demoLetterUnits, demoProfile } from "@/lib/demo-profile";
import { prepareLetter, prepareResume } from "@/lib/document-prep";
import { renderLetterDocx, renderResumeDocx } from "@/lib/docx/render";
import { contentDisposition } from "@/lib/file-name";
import { renderPdf } from "@/lib/pdf/render";
import { loadProfile } from "@/lib/profile-data";
import { route } from "@/lib/route";
import { loadSettings } from "@/lib/settings-data";
import { BUILT_IN_THEMES } from "@/lib/themes";

/** The Windows batch converter shipped next to the samples. */
const WINDOWS_SCRIPT = join(process.cwd(), "scripts", "docx-to-pdf.ps1");

/**
 * A ZIP with one Word document and the Chromium reference PDF for every
 * built-in theme, from the current profile and settings; two demo cover
 * letters and a references-enabled demo resume as stress fixtures; and the
 * Windows script that converts the Word files with desktop Word. Development
 * only: it is how a theme matrix is checked against Microsoft Word by hand.
 */
export const GET = route(async () => {
  if (process.env.NODE_ENV === "production") return new NextResponse("Not found", { status: 404 });
  const [profile, settings] = await Promise.all([loadProfile(), loadSettings()]);
  const today = new Date();
  const demo = demoProfile();
  const themeById = (id: string) => {
    const theme = BUILT_IN_THEMES.find((entry) => entry.id === id);
    if (!theme) throw new Error(`No built-in theme ${id}`);
    return theme;
  };

  const files: Record<string, Uint8Array> = {};
  for (const theme of BUILT_IN_THEMES) {
    const prepared = prepareResume({
      theme,
      profile,
      paper: settings.paper,
      today,
      language: settings.resumeLanguage,
      includeReferences: settings.includeRefs,
      sections: settings.resumeSections,
    });
    files[`docx/${theme.id}.docx`] = await renderResumeDocx(prepared);
    files[`chromium/${theme.id}.pdf`] = await renderPdf(`/print/theme/${theme.id}`);
  }

  // Demo stress fixtures: two cover letters (a plain and a banner theme) and
  // a sidebar resume whose main column ends in the nested references table.
  const extras: { kind: string; theme: string; note: string; docx: string; pdf: string }[] = [];
  for (const id of ["editorial", "signal"]) {
    const theme = themeById(id);
    const prepared = prepareLetter({
      theme,
      paper: settings.paper,
      basics: demo.basics,
      units: demoLetterUnits(),
      company: "Ledgerly",
      location: "Amsterdam",
      tone: Tone.WARM,
      date: demoLetterDate,
      dateFormat: settings.dateFormat,
      language: settings.resumeLanguage,
    });
    const docx = `docx/letter-${id}.docx`;
    const pdf = `chromium/letter-${id}.pdf`;
    files[docx] = await renderLetterDocx(prepared);
    files[pdf] = await renderPdf(`/print/theme/${id}/letter`);
    extras.push({ kind: "letter", theme: id, note: "demo profile, Ledgerly letter", docx, pdf });
  }

  const referencesTheme = themeById("studio");
  const references = prepareResume({
    theme: referencesTheme,
    profile: demo,
    paper: settings.paper,
    today,
    language: settings.resumeLanguage,
    includeReferences: true,
  });
  files["docx/references-studio.docx"] = await renderResumeDocx(references);
  files["chromium/references-studio.pdf"] = await renderPdf(`/print/theme/${referencesTheme.id}/references`);
  extras.push({
    kind: "references",
    theme: referencesTheme.id,
    note: "demo profile, references forced on",
    docx: "docx/references-studio.docx",
    pdf: "chromium/references-studio.pdf",
  });

  files["docx-to-pdf.ps1"] = new Uint8Array(await readFile(WINDOWS_SCRIPT));
  files["manifest.json"] = strToU8(
    JSON.stringify(
      {
        note: "Generated by /api/dev/word-samples. docx/ is the Word export, chromium/ the app's PDF for the same theme. Convert docx/ with desktop Word (docx-to-pdf.ps1) and compare with chromium/. The extras use the demo profile; the theme rows use the current profile.",
        generatedAt: today.toISOString(),
        paper: settings.paper,
        language: settings.resumeLanguage,
        includeReferences: settings.includeRefs,
        sections: settings.resumeSections,
        documents: BUILT_IN_THEMES.map((theme) => ({ theme: theme.id, name: theme.name, docx: `docx/${theme.id}.docx`, pdf: `chromium/${theme.id}.pdf` })),
        extras,
      },
      null,
      2,
    ),
  );

  const name = `dossier-samples-${settings.paper.toLowerCase()}-${today.toISOString().slice(0, 10)}.zip`;
  return new NextResponse(zipSync(files, { level: 6 }), {
    headers: { "content-type": "application/zip", "content-disposition": contentDisposition(name) },
  });
});
